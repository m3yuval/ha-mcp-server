#!/usr/bin/env node
// Generate docs/TOOLS.md from the real tool registrations (all capabilities on,
// against the fake HA). Run: npm run docs:tools   (after npm run build)
// test/docs.test.mjs fails if docs/TOOLS.md is out of date.
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { startFakeHA, startMcp } from "../test/helpers/harness.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
export const TOOLS_MD = path.resolve(here, "../../docs/TOOLS.md");

/** Which module registered a tool: probe each capability on its own. */
async function toolsFor(fake, env) {
  const srv = await startMcp({ fake, env: { ...env, CONFIG_DIR: process.cwd() } });
  try {
    return await srv.tools();
  } finally {
    await srv.stop();
  }
}

function kind(t) {
  const a = t.annotations ?? {};
  if (a.readOnlyHint) return "read-only";
  return a.destructiveHint ? "**destructive**" : "write";
}

function firstSentence(s = "") {
  // Protect abbreviations so "e.g." doesn't end the sentence.
  const one = s.replace(/\s+/g, " ").trim().replace(/\b(e\.g|i\.e|etc|vs)\./g, "$1\u0000");
  const m = one.match(/^(.+?[.!?])(\s|$)/);
  const out = (m ? m[1] : one).replace(/\u0000/g, ".");
  return (out.length > 220 ? out.slice(0, 217) + "…" : out).replace(/\|/g, "\\|");
}

function params(t) {
  const props = t.inputSchema?.properties ?? {};
  const req = new Set(t.inputSchema?.required ?? []);
  const names = Object.keys(props).map((k) => (req.has(k) ? `\`${k}\`*` : `\`${k}\``));
  return names.length ? names.join(", ") : "—";
}

export async function generate() {
  const fake = await startFakeHA();
  try {
    const base = await toolsFor(fake, {});
    const seen = new Set(base.map((t) => t.name));
    const groups = [["Always on (read-only)", "none", base]];
    for (const [title, flag, env] of [
      ["Actions", "`enable_actions`", { ENABLE_ACTIONS: "true" }],
      ["Config files", "`enable_config_files`", { ENABLE_CONFIG_FILES: "true" }],
      ["Management (Home Assistant Core + Supervisor)", "`enable_management`", { ENABLE_MANAGEMENT: "true" }],
    ]) {
      const tools = (await toolsFor(fake, env)).filter((t) => !seen.has(t.name));
      groups.push([title, flag, tools]);
    }
    const total = groups.reduce((n, g) => n + g[2].length, 0);
    const lines = [
      "# Tool catalog",
      "",
      "<!-- GENERATED by ha-mcp/scripts/gen-tools-doc.mjs — do not edit by hand. Run `npm run docs:tools` in ha-mcp/. -->",
      "",
      `${total} tools. Each group appears only when its add-on switch is on. \`*\` = required parameter.`,
      "Kinds come from the MCP annotations: *read-only* never changes anything; *write* changes state;",
      "**destructive** can remove data or disrupt the system (Claude is told to confirm first; the riskiest also need `confirm: true`).",
      "",
    ];
    for (const [title, flag, tools] of groups) {
      lines.push(`## ${title} (${tools.length})`, "", `Switch: ${flag}`, "", "| Tool | Kind | Parameters | Description |", "|---|---|---|---|");
      for (const t of [...tools].sort((a, b) => a.name.localeCompare(b.name))) {
        lines.push(`| \`${t.name}\` | ${kind(t)} | ${params(t)} | ${firstSentence(t.description)} |`);
      }
      lines.push("");
    }
    return lines.join("\n");
  } finally {
    await fake.stop();
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const md = await generate();
  await writeFile(TOOLS_MD, md);
  console.log(`wrote ${TOOLS_MD}`);
}
